BEGIN;

INSERT INTO reviews (guest_id, rating, title, body, status, review_type, created_at)
SELECT g.guest_id, v.rating, v.title, v.body, 'APPROVED', 'HOTEL', now() - (v.n || ' days')::interval
FROM (VALUES
  (1, 5, 'Прекрасный отель', 'Очень уютный номер, тихий двор и внимательный персонал. Обязательно вернёмся.', 18),
  (2, 5, 'Отличное расположение', 'В центре города, до всех достопримечательностей пешком. Завтрак разнообразный.', 15),
  (3, 4, 'Хорошее пребывание', 'Номер чистый и светлый. Немного шумно утром, но в целом всё понравилось.', 12),
  (4, 5, 'Рекомендую', 'Заселили быстро, дали бесплатный апгрейд. Вид из окна очень красивый.', 9),
  (5, 3, 'Нормально', 'Свойствам отеля соответствует, но завтрак мог бы быть лучше.', 6),
  (6, 4, 'Приятно удивил', 'Бутик-отель с характером. Персонал помог с трансфером в аэропорт.', 4),
  (7, 5, 'Лучший выбор', 'Останавливались всей семьёй. Всем понравилось, обязательно вернёмся снова.', 2),
  (1, 2, 'Есть замечания', 'Номер был готов не сразу, кондиционер работал шумно. Но расположение отличное.', 1)
) AS v(guest_id, rating, title, body, n)
JOIN guests g ON g.guest_id = v.guest_id
WHERE NOT EXISTS (
  SELECT 1 FROM reviews r
  WHERE r.review_type = 'HOTEL' AND r.title = v.title
);

COMMIT;
